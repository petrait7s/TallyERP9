import type { ReportModel, Row } from './types';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const CSS = `
 @page { size: A4; margin: 14mm; }
 body { font: 11px Arial, Helvetica, sans-serif; color: #000; margin: 0; padding: 12px; }
 h1 { font-size: 15px; margin: 0; text-align: center; }
 h2 { font-size: 12px; margin: 2px 0 0; text-align: center; font-weight: normal; }
 .sub { text-align: center; margin: 2px 0 10px; color: #333; }
 table { width: 100%; border-collapse: collapse; }
 th { text-align: left; border-bottom: 1px solid #000; border-top: 1px solid #000; padding: 3px 6px; }
 td { padding: 2px 6px; vertical-align: top; }
 .n { text-align: right; white-space: nowrap; }
 .b td { font-weight: bold; }
 .h td { font-weight: bold; text-decoration: underline; }
 .t td { border-top: 1px solid #000; border-bottom: 3px double #000; font-weight: bold; }
 .side { border-left: 1px solid #000; }
 .foot { margin-top: 14px; font-size: 9px; color: #555; text-align: center; }
`;

function cell(r: Row | undefined, i: number, numericFrom: number, extraClass = ''): string {
  const v = r?.cells[i] ?? '';
  const pad = i === 0 && r?.indent ? ` style="padding-left:${6 + r.indent * 14}px"` : '';
  return `<td class="${i >= numericFrom ? 'n' : ''} ${extraClass}"${pad}>${esc(v)}</td>`;
}
const rowClass = (r?: Row) => [r?.bold ? 'b' : '', r?.heading ? 'h' : '', r?.total ? 't' : ''].join(' ');

/** Self-contained printable HTML (A4) for a report model. */
export function reportToHtml(m: ReportModel, company: string): string {
  let body: string;
  if (m.layout === 'double') {
    const n = m.columns.length;
    const head = `<tr><th colspan="${n}">${esc(m.leftTitle ?? '')}</th><th colspan="${n}" class="side">${esc(m.rightTitle ?? '')}</th></tr>`;
    const rows = m.rows.map((l, i) => {
      const r = m.right?.[i];
      const lc = m.columns.map((_, ci) => cell(l, ci, m.numericFrom)).join('');
      const rc = m.columns.map((_, ci) => cell(r, ci, m.numericFrom, ci === 0 ? 'side' : '')).join('');
      return `<tr class="${rowClass(l)}">${lc}${rc}</tr>`;
    });
    body = `<table>${head}${rows.join('')}</table>`;
  } else {
    const head = `<tr>${m.columns.map((c, i) => `<th class="${i >= m.numericFrom ? 'n' : ''}">${esc(c)}</th>`).join('')}</tr>`;
    const rows = m.rows.map((r) => `<tr class="${rowClass(r)}">${m.columns.map((_, ci) => cell(r, ci, m.numericFrom)).join('')}</tr>`);
    body = `<table>${head}${rows.join('')}</table>`;
  }
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(m.title)}</title><style>${CSS}</style></head><body>
<h1>${esc(company)}</h1><h2>${esc(m.title)}</h2><div class="sub">${esc(m.subtitle ?? '')}</div>${body}
${m.note ? `<p><b>${esc(m.note)}</b></p>` : ''}<div class="foot">Generated by TallyLearn NGO (practice edition, unaffiliated with Tally Solutions)</div></body></html>`;
}
