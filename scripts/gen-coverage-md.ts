/** Writes docs/COVERAGE.md from content/coverage.json: npx vite-node scripts/gen-coverage-md.ts */
import { readFileSync, writeFileSync } from 'node:fs';

const cov = JSON.parse(readFileSync('content/coverage.json', 'utf8')) as Record<string, { title: string; screen: string; seed: string; lessons: string[] }>;
const lines = ['# Coverage: catalog feature -> screen -> seed -> lesson', '', 'Generated by `scripts/gen-coverage-md.ts` from `content/coverage.json` (lessons declare `covers`). The test `tests/learn.test.ts` fails if any item has no lesson.', '',
  '| Item | Feature | Screen | Seed | Lessons |', '|---|---|---|---|---|'];
for (const [k, v] of Object.entries(cov)) lines.push(`| ${k} | ${v.title} | ${v.screen} | ${v.seed} | ${v.lessons.join(', ') || '**MISSING**'} |`);
const missing = Object.values(cov).filter((v) => !v.lessons.length).length;
lines.push('', `Coverage: ${Object.keys(cov).length - missing}/${Object.keys(cov).length} catalog items have at least one lesson.`, '');
writeFileSync('docs/COVERAGE.md', lines.join('\n'));
console.log(lines.at(-2));
